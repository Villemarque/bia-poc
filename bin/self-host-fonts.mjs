// Regenerate the self-hosted Source Sans Pro files used by the site.
//
// Downloads the latin + latin-ext woff2 subsets (weights 400, 400 italic, 700,
// 900) from Google Fonts into static/fonts/ and writes the @font-face CSS.
//
//   node bin/self-host-fonts.mjs
//
// Requires network access. Re-run only if the font family/weights change.
import fs from "node:fs";
import path from "node:path";

const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";
const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Source+Sans+Pro:ital,wght@0,400;0,700;0,900;1,400&display=swap";
const outDir = path.resolve("static/fonts");
const keep = new Set(["latin", "latin-ext"]);

fs.mkdirSync(outDir, { recursive: true });

const css = await (await fetch(CSS_URL, { headers: { "user-agent": UA } })).text();

// split into `/* subset */ @font-face { ... }` blocks
const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
let out = "/* Self-hosted Source Sans Pro (latin, latin-ext) — generated by bin/self-host-fonts.mjs */\n";
let n = 0;

for (const [, subset, body] of blocks) {
  if (!keep.has(subset)) continue;
  const style = /font-style:\s*([a-z]+)/.exec(body)?.[1] ?? "normal";
  const weight = /font-weight:\s*(\d+)/.exec(body)?.[1] ?? "400";
  const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(body)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1];
  if (!url) continue;
  const name = `source-sans-pro-${weight}${style === "italic" ? "-italic" : ""}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  fs.writeFileSync(path.join(outDir, name), buf);
  out += `\n@font-face {\n\tfont-family: "Source Sans Pro";\n\tfont-style: ${style};\n\tfont-weight: ${weight};\n\tfont-display: swap;\n\tsrc: url("/fonts/${name}") format("woff2");\n\tunicode-range: ${range};\n}\n`;
  n++;
  console.log(`downloaded ${name} (${(buf.length / 1024).toFixed(0)} KB)`);
}

fs.writeFileSync(path.join(outDir, "source-sans-pro.css"), out);
console.log(`wrote static/fonts/source-sans-pro.css with ${n} @font-face blocks`);
